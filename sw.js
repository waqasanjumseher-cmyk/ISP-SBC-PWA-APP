// Minimal offline-first service worker for Zahidy Enterprise ERP.
// Caches the app shell so the ERP still opens (against local/cached data)
// without a network connection; Firestore itself handles its own
// online/offline sync separately once the page is running.
const CACHE_NAME = 'zahidy-erp-v1';
const APP_SHELL = [
  './erp.html',
  './manifest.json',
  './icon-192.png',
  './icon-512.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  // Network-first for same-origin app files so updates are picked up
  // quickly when online; fall back to cache when offline.
  if (event.request.method !== 'GET') return;
  event.respondWith(
    fetch(event.request)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
        return res;
      })
      .catch(() => caches.match(event.request))
  );
});
